-- crear la base de datos
CREATE DATABASE IF NOT EXISTS GaseosasDelValle;
USE GaseosasDelValle;

-- creacion de tablas
CREATE TABLE SEDES (
    id_sede BIGINT AUTO_INCREMENT PRIMARY KEY,
    nombre_sede VARCHAR(100) NOT NULL,
    ubicacion TEXT,
    capacidad_almacenamiento BIGINT,
    encargado VARCHAR(100)
);

CREATE TABLE CLIENTES (
    id_cliente BIGINT AUTO_INCREMENT PRIMARY KEY,
    nombre_completo VARCHAR(100) NOT NULL,
    identificacion VARCHAR(13) UNIQUE NOT NULL,
    direccion TEXT,
    telefono VARCHAR(8),
    correo_electronico VARCHAR(100)
);

CREATE TABLE PRODUCTOS (
    id_producto BIGINT AUTO_INCREMENT PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    categoria VARCHAR(100),
    precio DECIMAL(10, 2) NOT NULL,
    volumen_ml INT,
    stock_actual INT NOT NULL,
    stock_minimo INT NOT NULL
);

CREATE TABLE AUDITORIA_PRECIOS (
    id_auditoria BIGINT AUTO_INCREMENT PRIMARY KEY,
    id_producto BIGINT,
    precio_anterior DECIMAL(10, 2),
    precio_nuevo DECIMAL(10, 2),
    fecha_cambio TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (id_producto) REFERENCES PRODUCTOS(id_producto)
);

CREATE TABLE PEDIDOS (
    id_pedido BIGINT AUTO_INCREMENT PRIMARY KEY,
    fecha_pedido DATETIME DEFAULT CURRENT_TIMESTAMP,
    id_cliente BIGINT NOT NULL,
    id_sede BIGINT NOT NULL,
    total_sin_iva DECIMAL(10, 2) DEFAULT 0,
    total_con_iva DECIMAL(10, 2) DEFAULT 0,
    FOREIGN KEY (id_cliente) REFERENCES CLIENTES(id_cliente),
    FOREIGN KEY (id_sede) REFERENCES SEDES(id_sede)
);

CREATE TABLE DETALLE_PEDIDO (
    id_detalle_pedido BIGINT AUTO_INCREMENT PRIMARY KEY,
    id_pedido BIGINT NOT NULL,
    id_producto BIGINT NOT NULL,
    cantidad INT NOT NULL,
    subtotal DECIMAL(10, 2),
    FOREIGN KEY (id_pedido) REFERENCES PEDIDOS(id_pedido),
    FOREIGN KEY (id_producto) REFERENCES PRODUCTOS(id_producto)
);

